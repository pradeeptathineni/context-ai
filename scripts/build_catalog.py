#!/usr/bin/env python3
"""Generate the public personal library and legacy loadout browser from canonical sources."""
import json
import sys

from context_ai import ROOT, capability_definitions, catalogue, explain
from context_library import catalog_view, suggestions
WEB={'web-experience','react-web'}

def build():
    # No state argument: private maintenance events never enter the public static page.
    library=catalog_view()
    opportunities=suggestions()['suggestions']
    for profile in library['profiles']:
        profile.pop('suggestions')  # Published once in the derived opportunity view.
    options={row['id']:row for row in library['options']}
    concepts=library['concepts']
    rows=[]
    for id,d in sorted(catalogue().items(),key=lambda item:(item[0]!='essentials',item[0])):
        resolved=explain([id])
        registry=capability_definitions(resolved['options'])
        owners={}
        for entry in resolved['concerns'].values():
            owners[entry['owner_kind']]=owners.get(entry['owner_kind'],0)+1
        upstream=sorted({entry['upstream'] for entry in resolved['concerns'].values() if 'upstream' in entry})
        tools=sorted(registry[key]['command'] for key,req in resolved['capability_requirements'].items()
                     if registry[key]['kind']=='command' and req=='required')
        optional=sorted(registry[key]['command'] for key,req in resolved['capability_requirements'].items()
                        if registry[key]['kind']=='command' and req=='optional')
        files=sorted({p for paths in resolved['stages'].values() for p in paths})
        rows.append({'id':id,'kind':'web' if id in WEB else 'engineering','description':d['description'],
                     'composes':[x for x in resolved['composition'] if x!=id],'guidance':len(files),
                     'owners':owners,'upstream':upstream,'tools':tools,'optional_tools':optional,
                     'evidence':{'benefit':'unmeasured',
                                 'summary':options[id]['assessments'][-1]['scope'],
                                 'record':'; '.join(options[id]['assessments'][-1]['evidence'])}
                     if options[id]['assessments'] else {'benefit':'unmeasured'}})
    return {'concepts':concepts,'loadouts':rows,'library':library,'suggestions':opportunities}

def render(data):
    return '// Generated by scripts/build_catalog.py; do not edit by hand.\nwindow.CONTEXT_CATALOG = '+json.dumps(data,separators=(',',':'),sort_keys=True)+';\n'

if __name__=='__main__':
    target=ROOT/'examples/web/catalog.js'
    text=render(build())
    if sys.argv[1:]==['--check']:
        if target.read_text()!=text:
            print('examples/web/catalog.js is stale; run scripts/build_catalog.py',file=sys.stderr);sys.exit(1)
    else:
        target.write_text(text)
